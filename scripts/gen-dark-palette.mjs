// Generates src/dark-palette.css: under `.dark`, every Tailwind colour shade
// used by the UI is swapped with its mirror shade (50<->950, 100<->900, …), so
// the hard-coded light palette becomes a proper dark palette without touching
// any component. `.keep-dark` restores the original palette inside surfaces
// that are dark in both themes (the code editor).
//
//   node scripts/gen-dark-palette.mjs
import { readFileSync, writeFileSync } from "node:fs";

const theme = readFileSync("node_modules/tailwindcss/theme.css", "utf8");
const families = ["zinc", "emerald", "rose", "amber", "violet", "teal", "sky", "orange", "cyan", "lime", "fuchsia"];
const shades = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

const val = (fam, n) => {
  const m = theme.match(new RegExp(`--color-${fam}-${n}:\\s*([^;]+);`));
  if (!m) throw new Error(`missing ${fam}-${n}`);
  return m[1].trim();
};

let dark = "";
let keep = "";
for (const fam of families) {
  for (const n of shades) {
    const mirror = shades[shades.length - 1 - shades.indexOf(n)];
    dark += `  --color-${fam}-${n}: ${val(fam, mirror)};\n`;
    keep += `  --color-${fam}-${n}: ${val(fam, n)};\n`;
  }
}
// white surfaces become the darkest card tone; black stays black
dark += `  --color-white: ${val("zinc", 900)};\n`;
keep += `  --color-white: #fff;\n`;

const css = `/* GENERATED by scripts/gen-dark-palette.mjs — do not edit by hand. */
.dark {
${dark}}
/* Surfaces that stay dark in both themes (code editor). */
.dark .keep-dark {
${keep}}
`;
writeFileSync("src/dark-palette.css", css);
console.log("wrote src/dark-palette.css", css.length, "bytes");
